void CodeGenerator::genExit(ExitNode* node) {
    if (node->code) {
        genExpr(node->code);    // evaluate exit code -> rax
        emit("mov rdi, rax");   // exit code in rdi
    } else {
        emit("mov rdi, 0");     // default exit code 0
    }
    emit("mov rax, 0x2000001"); // exit syscall
    emit("syscall");
}

void CodeGenerator::genFuncCall(FuncCallNode* node) {
    // System V AMD64 calling convention
    // first 6 args go in registers:
    vector<string> argRegs = {"rdi", "rsi", "rdx", "rcx", "r8", "r9"};
    vector<string> floatRegs = {"xmm0","xmm1","xmm2","xmm3"};

    int intArgCount = 0;
    int floatArgCount = 0;

    for (int i =0 ; i < node->args.size(); i++){
        genExpr(node->args[i]);
        if(isFloatNode(node->args[i])){
            emit("movsd [rsp-" + to_string((i+1)*8) + "]");
        } else {
            emit ("push rax");
        }
    }

    // load into registers
    for (int i = node->args.size()-1; i >= 0; i--) {
        if (isFloatNode(node->args[i])){
            emit("movsd xmm" + to_string(floatArgCount++) + ", [rsp" + to_string((i+1)*8) +"]");
        } else {
            emit("pop " + argRegs[intArgCount++]);
        }
    }

    // save registers that might be in use
    emit("push r12");
    emit("push r13");

    // evaluate each argument and store temporarily on stack
    // then load into correct registers
    vector<int> argOffsets;

    for (int i = 0; i < node->args.size(); i++) {
        genExpr(node->args[i]);         // result in rax
        emit("push rax");               // save on stack temporarily
        argOffsets.push_back(i);    
    }
    
    // load args froms stack into registers (reverse order)
    for (int i = 0; i < node->args.size(); i++){
        if (i < 6) {
            emit("pop " + argRegs[i]);
        }else{
            // more than 6 args -. push onto stack (already there)
            break;
        }
    }

    // align stack to 16 bytes (Mac requirements)
    emit("mov r15, rsp");
    emit("and rsp, -16");

    // call the function
    emit("call " + node->funcName);

    emit("mov rsp, r15");
    // result is in rax after call
    emit("pop r13");
    emit("pop r12");
}

void CodeGenerator::genUnaryOp(UnaryOpNode* node) {
    cerr << "[DEBUG] genUnaryOp called postfix: " 
         << node->postfix << endl;
    if (node->postfix){
        // x++ or x--
        // need to get variable's address to modify it
        if (auto* ident = dynamic_cast<IdentifierNode*>(node->operand)){
            auto it = variables.find(ident->name);
            if (it ==  variables.end()){
                cerr << "[CodeGen Error] Undefined Variables: " << ident->name << endl;
                return;
            }
            int offset = it->second;

            // load current value
            emit("mov rax, [rbp-" + to_string(offset) + "]");

            if (node->op == TokenType::vriddhi){
                // x++
                emit("inc rax");             // increment
                emit("mov [rbp-"+ to_string(offset) + "], rax"); // store
                
            } else if(node->op == TokenType::kshaya){
                // x--
                emit("dec rax");             // increment
                emit("mov [rbp-"+ to_string(offset) + "], rax"); // store
            } 
        }
    } else {
        // prefix operator: !flag -x ++x --x
        if (node->op == TokenType::vriddhi) {
            // ++x
            if (auto* ident = dynamic_cast<IdentifierNode*>(node->operand)) {
                int offset = variables[ident->name];
                emit("mov rax, [rbp-" + to_string(offset) + "]");
                emit("inc rax");
                emit("mov [rbp-"+ to_string(offset) +"], rax");
            }
        }else if (node->op == TokenType::kshaya) {
            
            if (auto* ident = dynamic_cast<IdentifierNode*>(node->operand)) {
                int offset = variables[ident->name];
                emit("mov rax, [rbp-" + to_string(offset) + "]");
                emit("dec rax");
                emit("mov [rbp-"+ to_string(offset) +"], rax");
            }
        }else if (node->op == TokenType::viyoga) {
            // -x -> negate
            genExpr(node->operand);
            emit("neg rax");
        }else if (node->op == TokenType::na){
            // !x -> logical not
            genExpr(node->operand);
            emit("cmp rax, 0");
            emit("sete al");
            emit("movzx rax, al");
        }
    }
}

void CodeGenerator::genArrayLiteral(ArrayLiteralNode* node) {
    // allocate space for array on stack
    // each element takes 8 bytes
    int arraySize = node->elements.size() * 8;
    stackOffset += arraySize;
    int arrayBase = stackOffset;

    // store each element
    for (int i = 0; i < node->elements.size(); i++){
        genExpr(node->elements[i]);
        int elemOffset = arrayBase - (i * 8);
        emit("mov [rbp-"+ to_string(elemOffset) +"], rax");
    }

    // return address of first element in rax
    emit("lea rax, [rbp-" + to_string(arrayBase) + "]");
}

void CodeGenerator::genArrayAccess(ArrayAccessNode* node) {
    // find arrau base address
    auto it = variables.find(node->name);
    if (it == variables.end()){
        cerr << "[CodeGen Error] Undefined array: " << node->name << endl;
        return;
    }
    int baseOffset = it->second;

    // evaluate index - result in rax
    genExpr(node->index);

    // calculate element address
    // element address = base + (index * 8)
    emit("imul rax, 8");
    emit("mov rbx, rbp");
    emit("sub rbx, " + to_string(baseOffset));  // rbx = base address
    emit("sub rbx, rax");       // rbx = element address 

    if (node->value != nullptr){
        // assigment: arr[0] = 10
        emit("mov r14, rbx");               // save element address
        genExpr(node->value);           // evaluate value -> rax
        emit("mov [r14], rax");         // store value
    } else {
        // access: arr[i] mudraya
        emit("mov rax, [rbx]");
    }
}
void CodeGenerator::genInput(InputNode* node) {
    // find variable on stack
    auto it = variables.find(node->name);
    if (it == variables.end()){
        cerr << "[CodeGen Error] Undefined variable: " << node->name << endl;
        return;
    }
    int offset = it->second;

    // allocate buffer on stack for input
    emit("sub rsp, 32");        // 32 byte input buffer
    
    // read syscall
    emit("mov rax, 0x2000003");     // Mac read syscall
    emit("mov rdi, 0");             // stdin = 0
    emit("lea rsi, [rsp]");         // buffer address
    emit("mov rdx, 32");            // max byte to read
    emit("syscall");                // rax

    // convert string to integer
    // buffer at [rsp], length in rax
    emit("mov rcx, 0");             // result = 0
    emit("mov r8, 0");              // index = 0
    emit("mov r9, rax");            // r9 = length (bytes read)
    emit("dec r9");                 // ignore newline at end

    string convLoop = newLabel();
    string convDone = newLabel();

    emitLabel(convLoop);
    emit("cmp r8, r9");             // index == length?
    emit("jge " + convDone);        // yes -> done

    emit("movzx rax, byte [rsp+r8]");       // load character
    emit("sub rax, 48");                    // convert ASCII to digit
    emit("imul rcx, 10");                   // result *= 10
    emit("add rcx, rax");                   // result += digit
    emit("inc r8");                         // index++
    emit("jmp " + convLoop);

    emitLabel(convDone);

    // store result in variables
    emit("mov [rbp-" + to_string(offset) + "], rcx");

    // restore stack
    emit("add rsp, 32");
}

void CodeGenerator::genNewExpr(NewNode* node){
    // allocate memory on heap using mmap syscall (Mac)
    // mmap (NULL, size, PROT_READ | PROT_WRITE, MAP_PRIVATE|MAP_ANONYMOUS, -1, 0)

    int size = typeSize(node->type);

    emit("mov rax, 0x20000C5");         // mmap syscall (Mac)
    emit("mov rdi, 0");                 // addr = NULL (let OS choose)
    emit("mov rsi, " +to_string(size)); // size
    emit("mov rdx, 3");                 // PROT_READ | PROT_WRITE
    emit("mov r10, 0x1002");            // MAP_PRIVATE | MAP_ANONYMOUS
    emit("mov r8, -1");                 // fd = -1
    emit("mov r9, 0");                  // offset = 0         
    emit("syscall");                    // rax = pointer to allocated memory
    // rax now has the heap address
}

void CodeGenerator::genFreeStmt(FreeNode* node){
    // find variable holding the pointer
    auto it = variables.find(node->name);
    if (it == variables.end()){
        cerr << "[CodeGen Error] Undefined variable: " << node->name << endl;
        return;
    }
    int offset = it->second;

    // load pointer from variable
    emit("mov rdi, [rbp-"+ to_string(offset ) + "]");    // addres to free
    emit("mov rsi, 8");                                  // size (same as allocated)
    emit("mov rax, 0x2000049");                          // munmap syscall (Mac)
    emit("syscall");                                     // free the memory
}

void CodeGenerator::genSwitch(SwitchNode* node){
    // evaluate switch expressions - result in rax
    genExpr(node->expression);
    emit("mov r12, rax");                   // save switch value in r12

    string switchEnd = newLabel();
    vector<string> caseLabels;

    // generate label for each case
    for (int i = 0; i < node->cases.size(); i++){
        caseLabels.push_back(newLabel());
    }

    // generate comparisons
    for (int i = 0; i < node->cases.size(); i++){
        CaseNode* c = node->cases[i];

        if (c->value == nullptr) {
            // adya (default) - always jump to it
            emit("jmp " + caseLabels[i]);
        } else {
            // evaluate case value
            genExpr(c->value);
            emit("cmp r12, rax");               // compare switch value
            emit("je " + caseLabels[i]);        // if match -> jump to case
        }
    }

    // no case matched and no default -> jump to end
    emit("jmp " + switchEnd);

    // generate case bodies
    for (int i = 0; i < node->cases.size(); i++){
        emitLabel(caseLabels[i]);
        genBlock(node->cases[i]->body);
        emit("jmp " + switchEnd);           // viram -> jump to end
    }

    emitLabel(switchEnd);
}