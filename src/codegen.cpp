string CodeGenerator::getOutput(){
    stringstream final;
    final << "global _main\n\n";
    final << "section .data\n";
    final << dataSection.str();
    final << "\nsection .text\n";
    final << output.str();
    return final.str();
}

void CodeGenerator::writeToFile(string filename) {
    ofstream file(filename);
    file << getOutput();
    file.close();
}

void CodeGenerator::genProgram(ProgramNode* node) {
    output <<"; Generated by Sans Compiler \n\n";

    dataSection << "    dec_mult dq 100.0\n";

    // forward declare all functions
    for(auto* decl: node->declarations) {
        if (auto* f = dynamic_cast<FuncDeclNode*>(decl)){
            if (f->name != "mukhya")
                output << "global " << f->name << "\n";
        }
    }

    for (auto* decl : node->declarations){
        if (auto* f = dynamic_cast<FuncDeclNode*>(decl))
            genFuncDecl(f);
    }
}

bool CodeGenerator::isFloatNode(ASTNode* node){
    if (auto* lit = dynamic_cast<LiteralNode*>(node))
        return lit->type == TokenType::dashamlav_lit;
    if (auto* ident = dynamic_cast<IdentifierNode*>(node))
        return isFloatVar.count(ident->name) && isFloatVar[ident->name];
    if (auto* bin = dynamic_cast<BinaryOpNode*>(node))
        return isFloatNode(bin->left) || isFloatNode(bin->right);
    return false;
}

int CodeGenerator::calculateStackSize(BlockNode* body, vector<ParamNode*>& params){
    int size = 0;

    // params
    size += params.size() * 8;

    // count variables in block
    if  (!body) return size;
    for (auto* stmt : body->statements){
        if (auto* v = dynamic_cast<VarDeclNode*>(stmt)){
            if (v->type.substr(0,6) == "sarani") {
                // array - need to know element count
                if (auto* arr = dynamic_cast<ArrayLiteralNode*>(v->initializer))
                    size += arr->elements.size() * 8;
            } else {
                size += 8;
            }
        }
    }

    // add extra space for temporaries
    size += 64;

    return size;
}

void CodeGenerator::genFuncDecl(FuncDeclNode* node) {
    variables.clear();
    variableTypes.clear();
    stackOffset = 0;
    currentFunction = node->name;
    string funcName = (node->name == "mukhya") ? "_main" : node->name;
    
    output << "\n" << funcName << ":\n";

    emit("push rbp"); //save caller's base pointer
    emit("mov rbp, rsp"); // set our base pointer
    
    // calculate stack size needed
    int stackSize = calculateStackSize(node->body, node->params);

    // align to 16 bytes 
    if (stackSize % 16 != 0){
        stackSize += 16 - (stackSize % 16);
    }

    // minimum 32 bytes
    if (stackSize < 32) stackSize = 32;

    // reserve space for local variables
    // we use 128 bytes for now - improve later
    emit("sub rsp, " + to_string(stackSize)); // move stack pointer down
    
    // handle fucntion parameters
    // System V AMD64 calling convetion:
    // first 6 args come in: rdi,rsi,rdx,rcx,r8,r9
    vector<string> argRegs = {"rdi", "rsi", "rdx", "rcx", "r8", "r9"};
    for(int i = 0; i < node->params.size() && i < 6; i++){
        stackOffset += 8;
        variables[node->params[i]->name] = stackOffset;
        emit("mov [rbp-" + to_string(stackOffset) + "], " + argRegs[i]);
    }

    // generate function body
    genBlock(node->body);

}

void CodeGenerator::genBlock(BlockNode* node) {
    if (!node) return;

    // generate each statement in the block
    for (auto* stmt : node->statements){
        genStatement(stmt);
    }
}

void CodeGenerator::genStatement(ASTNode* node) {
    if (!node) return;

    if (auto* n = dynamic_cast<VarDeclNode*>(node))             genVarDecl(n);
    else if (auto* n = dynamic_cast<AssignNode*>(node))         genAssign(n);
    else if (auto* n = dynamic_cast<PrintNode*>(node))          genPrint(n);
    else if (auto* n = dynamic_cast<InputNode*>(node))          genInput(n);
    else if (auto* n = dynamic_cast<IfNode*>(node))             genIf(n);
    else if (auto* n = dynamic_cast<WhileNode*>(node))          genWhile(n);
    else if (auto* n = dynamic_cast<ForNode*>(node))            genFor(n);
    else if (auto* n = dynamic_cast<ReturnNode*>(node))         genReturn(n);
    else if (auto* n = dynamic_cast<BreakNode*>(node))          genBreak(n);
    else if (auto* n = dynamic_cast<ContinueNode*>(node))       genContinue(n);
    else if (auto* n = dynamic_cast<ExitNode*>(node))           genExit(n);
    else if (auto* n = dynamic_cast<FuncCallNode*>(node))       genFuncCall(n);
    else if (auto* n = dynamic_cast<UnaryOpNode*>(node))        genUnaryOp(n);
    else if (auto* n = dynamic_cast<BinaryOpNode*>(node))       genBinaryOp(n);
    else if (auto* n = dynamic_cast<FuncDeclNode *>(node))      genFuncDecl(n);
    else if (auto* n = dynamic_cast<ArrayAccessNode*>(node))    genArrayAccess(n);
    else if (auto* n = dynamic_cast<NewNode*>(node))            genNewExpr(n);
    else if (auto* n = dynamic_cast<FreeNode*>(node))           genFreeStmt(n);
    else if (auto* n = dynamic_cast<SwitchNode*>(node))         genSwitch(n);
}

void CodeGenerator::genExpr(ASTNode* node) {
    if (!node) return;

    if (auto* n = dynamic_cast<LiteralNode*>(node))
        genLiteral(n);
    else if (auto* n = dynamic_cast<IdentifierNode*>(node))
        genIdentifier(n);
    else if (auto* n = dynamic_cast<BinaryOpNode*>(node))
        genBinaryOp(n);
    else if (auto* n = dynamic_cast<UnaryOpNode*>(node))
        genUnaryOp(n);
    else if (auto* n = dynamic_cast<FuncCallNode*>(node))
        genFuncCall(n);
    else if (auto* n = dynamic_cast<ArrayLiteralNode*>(node))
        genArrayLiteral(n);
    else if (auto* n = dynamic_cast<ArrayAccessNode*>(node))  
        genArrayAccess(n);
    else if (auto* n = dynamic_cast<NewNode*>(node))
        genNewExpr(n);
}

void CodeGenerator::genLiteral(LiteralNode* node) {
    if (node->type == TokenType::purnank_lit){
        // integer Literal
        emit("mov rax, " + node->value);
    }
    else if (node->type == TokenType::satya){
        //boolean true = 1
        emit("mov rax, 1");
    }
    else if (node->type == TokenType::asatya){
        //boolean true = 0
        emit("mov rax, 0");
    }
    else if (node->type == TokenType::aksarmala_lit){
        //string literal - need to store in .data and load address
        string label = newStringLabel();
        dataSection << "   " << label << " db \"" << node->value << "\", 0\n";
        emit("lea rax, [rel " + label + "]");
    }
    else if (node->type == TokenType::dashamlav_lit) {
        string label = newLabel();
        dataSection << "    " << label << " dq " << node->value << "\n";
        emit("movsd xmm0, [rel " + label + "]"); 
        // leave result of xmm0 for float operations 
    }
    else if (node->type == TokenType::aksar_lit) {
        // store ASCII value of character
        char ch = node->value[0];
        emit("mov rax, " + to_string((int)ch));
    }

}

void CodeGenerator::genIdentifier(IdentifierNode* node) {
    // look up where this variable lives on stack
    auto it = variables.find(node->name);
    if (it == variables.end()){
        cerr << "[CodeGen Error] Undefined variable: " << node->name << endl;
        return;
    }

    int offset = it->second;

    if (isFloatVar.count(node->name) && isFloatVar[node->name]){
        emit("movsd xmm0, [rbp-"+ to_string(offset) +"]");
    } else {
        // load value from stack into rax
        emit("mov rax, [rbp-" + to_string(offset) + "]");
    }
}

void CodeGenerator::genVarDecl(VarDeclNode* node) {

    variableTypes[node->varName] = node->type;

    int size = typeSize(node->type);
    stackOffset += size;
    variables[node->varName] = stackOffset;

    if (node->type == "dashamlav") {
        isFloatVar[node->varName] = true;
        if (node->initializer) {
            genExpr(node->initializer);
            // result in xmm0 
            emit("movsd [rbp-"+ to_string(stackOffset) + "], xmm0");
        } else {
            emit("pxor xmm0, xmm0");     // zero
            emit("movsd [rbp-" + to_string(stackOffset) + "], xxm0");
        }
        return;
    }

    if (node->type.substr(0,6) == "sarani") {
        // array declaration
        if (node->initializer) {
            if (auto* arr = dynamic_cast<ArrayLiteralNode*>(node->initializer)) {
                int count = arr->elements.size();
                stackOffset += count * 8;
                int arrayBase = stackOffset;

                // store each element 
                for (int i = 0; i < arr->elements.size(); i++) {
                    genExpr(arr->elements[i]);
                    int elemOffset = arrayBase - (i * 8);
                    emit("mov [rbp-" + to_string(elemOffset) + "], rax");
                }

                // store base address in variable map
                variables[node->varName] = arrayBase;
            }
        }
        return;
    }

    // if there's an initializer, evaluate and store it
    if (node->initializer) {
        // evaluate expression - result goes into rax
        genExpr(node->initializer);
        //store rax value onto stack at variable's location
        emit("mov [rbp-" + to_string(stackOffset) + "], rax");
    } else {
        // no initalizer - deafult to 0
        emit("mov qword [rbp-" + to_string(stackOffset) + "], 0");
    }
}

void CodeGenerator::genAssign(AssignNode* node) {
    // evaluate right side - result goes into rax
    genExpr(node->value);

    //find where variable lives on stack
    auto it = variables.find(node->name);
    int offset = it->second;

    if (isFloatVar.count(node->name) && isFloatVar[node->name]) {
        if (node->op == TokenType::sthapna) {
            emit("movsd [rbp-" + to_string(offset) +"], xmm0");
        } else if (node->op == TokenType::yoga_sthapana){
            emit("movsd xmm1,[rbp-" + to_string(offset) + "]");
            emit("addsd xmm1, xmm0");
            emit("movsd [rbp-" + to_string(offset) +"], xmm1");
        } else if (node->op == TokenType::viyoga_sthapana){
            emit("movsd xmm1,[rbp-" + to_string(offset) + "]");
            emit("subsd xmm1, xmm0");
            emit("movsd [rbp-" + to_string(offset) +"], xmm1");
        } else if (node->op == TokenType::gunan_sthapana){
            emit("movsd xmm1,[rbp-" + to_string(offset) + "]");
            emit("mulsd xmm1, xmm0");
            emit("movsd [rbp-" + to_string(offset) +"], xmm1");
        } else if (node->op == TokenType::bhaga_sthapana){
            emit("movsd xmm1,[rbp-" + to_string(offset) + "]");
            emit("divsd xmm1, xmm0");
            emit("movsd [rbp-" + to_string(offset) +"], xmm1");
        }
        return;
    }


    if (it == variables.end()) {
        cerr << "[CodeGen Error] Undefined variable: " << node->name << endl;
        return;
    }

    // handle compound assigment operators
    if (node->op == TokenType::sthapna) {
        // x = expr -> just store rax
        emit("mov [rbp-" + to_string(offset) + "], rax");
    }
    else if (node->op == TokenType::yoga_sthapana) {
        // x += expr
        emit("mov rbx, [rbp-"+ to_string(offset) + "]");
        emit("add rbx, rax");
        emit("mov [rbp-"+ to_string(offset) + "], rbx");

    }else if (node->op == TokenType::viyoga_sthapana) {
        // x -= expr
        emit("mov rbx, [rbp-"+ to_string(offset) + "]");
        emit("sub rbx, rax");
        emit("mov [rbp-"+ to_string(offset) + "], rbx");

    }else if (node->op == TokenType::gunan_sthapana) {
        // x *= expr
        emit("mov rbx, [rbp-"+ to_string(offset) + "]");
        emit("imul rbx, rax");
        emit("mov [rbp-"+ to_string(offset) + "], rbx");
    }
    else if (node->op == TokenType::bhaga_sthapana) {
        // x /= expr
        emit("add rbx, rax");   // save divisor
        emit("mov rax, [rbp-"+ to_string(offset) + "]");
        emit("cqo");            // sign extend rax into rdx:rax
        emit("idiv rbx");       // rax = rax / rbx 
        emit("mov [rbp-"+ to_string(offset) + "], rax");
    }else if (node->op == TokenType::shesh_sthapana) {
        // x %= expr
        emit("add rbx, rax");   //save divisor
        emit("mov rax, [rbp-"+ to_string(offset) + "]");
        emit("cqo");            // sign extend
        emit("idiv rbx");       // remainder in rdx
        emit("mov [rbp-"+ to_string(offset) + "], rbx");
    }
}

void CodeGenerator::genBinaryOp(BinaryOpNode* node) {

    bool floatOp = isFloatNode(node->left) || isFloatNode(node->right);

    if (floatOp) {
        // evalutate left -> xmm0
        genExpr(node->left);
        emit("movsd [rbp-128], xmm0");      // save left temporarily

        // evluate right -> xmm0
        genExpr(node->right);
        emit("movsd xmm1, xmm0");           // xmm1 = right

        // restore left
        emit("movsd xmm0, [rbp-128]");      // xmm0 = left

        switch (node->op) {
            //arithmetic
            case TokenType::yoga:
                emit("addsd xmm0, xmm1");
                break;
    
            case TokenType::viyoga:
                emit("subsd xmm0, xmm1");
                break;
    
            case TokenType::gunan:
                emit("mulsd xmm0, xmm1");
                break;
            
            case TokenType::bhaga:
                emit("divsd xmm0, xmm1");
                break;

            // comparison -> result in rax
            case TokenType::adhik:
            case TokenType::sym_adhik: 
                emit("ucomisd xmm0, xmm1");
                emit("seta al");    // al = 1 if xmm0 > xmm1
                emit("movzx rax, al"); // zero extend al to rax
                break;
            
            case TokenType::nyun:
            case TokenType::sym_nyun:
                emit("ucomisd xmm0, xmm1");
                emit("setb al");
                emit("movzx rax, al");
                break;
            
            case TokenType::sam:
            case TokenType::sym_sam:
                emit("cmp rax, rbx");
                emit("setne al");
                emit("movzx rax, al");
                break;
            default:
                break;
        }
        return;
    }

    // evaluate left side -> result in rax
    genExpr(node->left);
    emit("push rax");       // save left resut to stack

    // evaluate right side -> result in rax
    genExpr(node->right);
    emit("mov rbx, rax");

    // restore left into rax
    emit("pop rax");

    // now: rax = left, rbx = right
    // perform operation

    switch (node->op) {
        //arithmetic
        case TokenType::yoga:
            emit("add rax, rbx");
            break;

        case TokenType::viyoga:
            emit("sub rax, rbx");
            break;

        case TokenType::gunan:
            emit("imul rax, rbx");
            break;
        
        case TokenType::bhaga:
            emit("cpo");
            emit("idiv rbx");
            //resut in rax
            break;
        case TokenType::shesh:
            emit("cqo");
            emit("idiv rbx");
            emit("mov rax, rdx"); // remainder in rdx -> move to rax
            break;
        
        // comparison operators -> result is 0 or 1 in rax
        case TokenType::adhik:
        case TokenType::sym_adhik: 
            emit("cmp rax, rbx");
            emit("setg al");    // al = 1 if rax > rbx
            emit("movzx rax, al"); // zero extend al to rax
            break;
        
        case TokenType::nyun:
        case TokenType::sym_nyun:
            emit("cmp rax,rbx");
            emit("setl al");
            emit("movzx rax, al");
            break;

        case TokenType::asam:
        case TokenType::sym_asam:
            emit("cmp rax, rbx");
            emit("setne al");
            emit("movzx rax, al");
            break;
        
        case TokenType::adhik_sam:
        case TokenType::sym_adhik_sam:
            emit("cmp rax, rbx");
            emit("setge al");
            emit("movzx rax, al");
            break;

        case TokenType::nyun_sam:
        case TokenType::sym_nyun_sam:
            emit("cmp rax, rbx");
            emit("setle al");
            emit("movzx rax, al");
         
        // Logical Operators
        case TokenType::tatha: // && (AND)
            emit("and rax, rbx");
            break;
        
        case TokenType::va:
            emit("or rax, rbx");

        default:
            cerr << "[CodeGen Error] Unkown binary operator" << endl;
            break;
    }

}

